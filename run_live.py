"""
Боевой прогон heal-петли против ЖИВОЙ 1С.
Перед запуском:
  1) открыта форма-раннер (ВнешняяОбработкаИИАгент) с ВКЛЮЧЁННЫМ таймером
     (кнопка ВключитьЦикличныйПерезапуск);
  2) LM Studio запущен на :1235;
  3) main.py НЕ запущен (иначе подерётесь за error.txt).
Запуск:  python run_live.py
"""
from src.onec.glue import heal, Real1CRunner
from src.core.config import CFG

# намеренно битый модуль: опечатка Каждного (-> Qwen) + КонецДля (-> delint).
# Точка входа ВыполнитьЗадачу(ЛогВыполнения) — как ждёт форма-раннер.
# В конце пишем "ГОТОВО", чтобы форма вернула OK при успехе.
BROKEN = (
    "Процедура ВыполнитьЗадачу(ЛогВыполнения) Экспорт\n"
    "    Итог = 0;\n"
    "    Массив = Новый Массив;\n"
    "    Массив.Добавить(10); Массив.Добавить(20);\n"
    "    Для Каждного Э Из Массив Цикл\n"
    "        Итог = Итог + Э;\n"
    "    КонецДля;\n"
    "    ЛогВыполнения = ЛогВыполнения + \"Итог=\" + Строка(Итог) + \"; ГОТОВО\";\n"
    "КонецПроцедуры\n"
)

if __name__ == "__main__":
    runner = Real1CRunner(CFG)
    print("=== ЖИВОЙ ПРОГОН ===")
    res = heal(BROKEN, runner, max_iters=3)
    print("trace:", res["trace"])
    print("ok:", res["ok"], "| причина:", res.get("reason", "-"))
    print("=== ИТОГ МОДУЛЯ ===")
    print(res["code"])

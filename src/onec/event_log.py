#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Чтение Журнала регистрации 1С — то, что пользователь ВИДИТ во всплывающих окнах
1С:Предприятия (ошибки инициализации модуля, критичные сообщения расширений,
"уже существует объект с именем...", ошибки фоновых заданий и т.п.), а агент
через run_module/deploy_module НЕ видит вообще (в консоль/лог MCP это не попадает).
Поймано вживую: без этого инструмента приходилось просить пользователя пересказывать
текст всплывающих окон скриншотами.

Платформенный механизм БЕЗ зависимости от БСП — ВыгрузитьЖурналРегистрации(ИмяФайла,
Фильтр), НО с двумя граблями, набитыми вживую:

  1. run_module выполняется в headless-обработке с ПРИНУДИТЕЛЬНЫМ безопасным режимом
     (защита от произвольного файлового I/O из LLM-кода). ВыгрузитьЖурналРегистрации
     как "доверенная" платформенная функция ЗАПИСЬ разрешает, а вот ЛЮБОЕ чтение
     файла обратно из BSL (ЧтениеXML.ОткрытьФайл, ДвоичныеДанные(Путь),
     ЧтениеТекста(Путь) — ВСЕ они) падает с "Установлен безопасный режим".
     Решение: BSL-снипет только ПИШЕТ файл в известный путь ВНУТРИ runtime_dir
     проекта (не Windows\\Temp — сам процесс имеет туда доступ на запись), а
     разбирает XML уже ЭТОТ Python-модуль, СНАРУЖИ песочницы 1С.
  2. Фильтр.Уровень принимает МАССИВ значений перечисления УровеньЖурналаРегистрации
     (УровеньЖурналаРегистрации.Ошибка / .Предупреждение), НЕ строки "Ошибка"/
     "Предупреждение" — со строками фильтр молча игнорируется и выгружает ВСЕ
     уровни (в т.ч. Information), что выглядит как "фильтр не сработал", хотя
     ошибки в коде не было — просто неверный тип значения внутри Структуры.
  3. Фильтр.Пользователь, В ОТЛИЧИЕ от Уровня, ПРИНИМАЕТ обычную строку с логином
     (например "Администратор (ОрловАВ)") и реально фильтрует — проверено вживую:
     4476 событий без фильтра за тот же час -> 972 с фильтром по одному логину.
     Полезно резать фоновый шум от других пользователей/фоновых заданий (Access
     management и т.п. — их UserName вообще пустой, отфильтровываются заодно).

Схема экспортированного XML: корень <v8e:EventLog xmlns:v8e="http://v8.1c.ru/eventLog">,
дети <v8e:Event> с полями Level/Date/ApplicationName/Event/EventPresentation/
User/UserName/Computer/Metadata/MetadataPresentation/Comment/Data/DataPresentation.
"""
import xml.etree.ElementTree as ET
from pathlib import Path

_NS = {"v8e": "http://v8.1c.ru/eventLog"}


def build_export_bsl(export_path: str, minutes_back: int = 30, user: str = None) -> str:
    """BSL-снипет для run_module: выгружает Ошибка+Предупреждение за minutes_back
    минут в export_path (путь ДОЛЖЕН быть внутри runtime_dir проекта — headless
    процесс имеет туда доступ на запись; при этом safe mode не даёт прочитать
    файл обратно из BSL, поэтому дальше его парсит Python, см. parse_export).
    user — логин ИБ (как в строке подключения Usr=) для отсечения чужого шума;
    без него выгружаются события ВСЕХ пользователей (в т.ч. фоновые задания)."""
    seconds = minutes_back * 60
    user_line = ""
    if user:
        escaped = user.replace('"', '""')
        user_line = f'\tФильтр.Вставить("Пользователь", "{escaped}");\n'
    return (
        "Процедура ВыполнитьЗадачу(ЛогВыполнения) Экспорт\n"
        f'\tВрФайл = "{export_path}";\n'
        "\tФильтр = Новый Структура;\n"
        f"\tФильтр.Вставить(\"ДатаНачала\", ТекущаяДата() - {seconds});\n"
        "\tУровни = Новый Массив;\n"
        "\tУровни.Добавить(УровеньЖурналаРегистрации.Ошибка);\n"
        "\tУровни.Добавить(УровеньЖурналаРегистрации.Предупреждение);\n"
        "\tФильтр.Вставить(\"Уровень\", Уровни);\n"
        f"{user_line}"
        "\tВыгрузитьЖурналРегистрации(ВрФайл, Фильтр);\n"
        '\tЛогВыполнения = ЛогВыполнения + "Выгружено" + Символы.ПС;\n'
        '\tЛогВыполнения = ЛогВыполнения + "ГОТОВО";\n'
        "КонецПроцедуры\n"
    )


def parse_export(export_path: str, limit: int = 30) -> list:
    """Разбирает XML-выгрузку журнала (см. build_export_bsl) в компактный список
    {date, level, application, event, event_presentation, metadata, user_name, comment}.
    Возвращает ПОСЛЕДНИЕ limit событий (обычно самые релевантные — то, что
    произошло только что). Удаляет сам файл после разбора."""
    p = Path(export_path)
    if not p.exists():
        return []
    try:
        # utf-8-sig: терпит BOM, если 1С его напишет (обычная utf-8 упала бы на
        # ET.fromstring с "XML or text declaration not at start of entity"),
        # и ведёт себя как обычный utf-8, если BOM нет — безопасная замена.
        root = ET.fromstring(p.read_text(encoding="utf-8-sig"))
        events = []
        for ev in root.findall("v8e:Event", _NS):
            def txt(tag):
                el = ev.find(f"v8e:{tag}", _NS)
                return (el.text or "").strip() if el is not None and el.text else ""
            events.append({
                "date": txt("Date"),
                "level": txt("Level"),
                "application": txt("ApplicationName"),
                "event": txt("Event"),
                "event_presentation": txt("EventPresentation"),
                "metadata": txt("Metadata"),
                "user_name": txt("UserName"),
                "comment": txt("Comment")[:500],
            })
        return events[-limit:]
    finally:
        p.unlink(missing_ok=True)

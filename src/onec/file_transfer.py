#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Передача файлов на машину, где реально живёт 1С, ЧЕРЕЗ РАННЕР.

Зачем. Пользователь подключается к рабочим базам УДАЛЁННО, поэтому сервер 1С не
видит локальных путей агента. Поймано живьём:

    ВнешниеОбработки.Подключить("D:\\1сБазы\\...\\Обработка.epf")
    -> Неправильный путь к файлу [ОшибкаДоступаКЛокальномуФайлу]

То есть собрать .epf локально можно, а проверить или подключить его в базе —
нет. Единственный канал, который уже есть и работает, — раннер: он исполняет BSL
внутри сеанса 1С. Значит файл можно передать как данные.

Механика: файл режется на куски, каждый кусок едет в base64 внутри текста
задания, на той стороне декодируется в ДвоичныеДанные и пишется отдельным
part-файлом, в конце куски склеиваются ОбъединитьФайлы и подкаталог с кусками
убирается. Куски нужны потому, что задание — это исходник BSL, и гнать мегабайт
одной строкой неразумно; заодно видно, на каком куске оборвалось.

КУДА КЛАДЁМ. По умолчанию — ВРЕМЕННЫЙ КАТАЛОГ СЕРВЕРА, и путь вычисляется НА
ТОЙ СТОРОНЕ (КаталогВременныхФайлов()), а не задаётся отсюда. Причины две:
произвольный путь вроде C:\\<что-то> на боевом сервере агент может не создать —
прав нет; и незачем оставлять на рабочей машине каталоги с говорящими именами.
Временный каталог существует всегда. Фактический путь возвращается в результате.
"""
import base64
import hashlib
from pathlib import Path

# 128 КБ сырых данных -> ~176 КБ base64 -> ~190 КБ текста задания. Размер выбран
# так, чтобы задание оставалось читаемым для транспорта и не упиралось в лимиты.
CHUNK_BYTES = 128 * 1024

# Длина куска строкового литерала в BSL. Одна строка на 176 КБ теоретически
# допустима, но и конфигуратор, и логи с такой работают плохо.
LITERAL_CHUNK = 900

BS = chr(92)          # обратный слэш: в BSL он НЕ экранируется, это обычный символ
Q = '"'


def _bsl_literal(b64: str, var: str = "Б64") -> str:
    """base64 -> набор присваиваний Б64 = Б64 + "...", чтобы не рожать монолит."""
    lines = ["\t%s = %s%s;" % (var, Q, Q)]
    for i in range(0, len(b64), LITERAL_CHUNK):
        lines.append("\t%s = %s + %s%s%s;" % (var, var, Q, b64[i:i + LITERAL_CHUNK], Q))
    return "\n".join(lines)


def _bsl_str(v: str) -> str:
    """В BSL нет экранирования обратного слэша, но кавычку надо удвоить."""
    return (v or "").replace(Q, Q + Q)


def _prolog(remote_dir: str, tag: str) -> str:
    """Общее начало обоих заданий: вычислить каталог назначения на той стороне."""
    return "\n".join([
        '\tКаталог = "%s";' % _bsl_str(remote_dir),
        '\tЕсли ПустаяСтрока(Каталог) Тогда',
        '\t\tКаталог = КаталогВременныхФайлов();',
        '\tКонецЕсли;',
        '\tЕсли Не Прав(Каталог, 1) = "%s" Тогда' % BS,
        '\t\tКаталог = Каталог + "%s";' % BS,
        '\tКонецЕсли;',
        '\tЧастиКаталог = Каталог + "%s";' % _bsl_str(tag),
    ])


def chunk_task(remote_dir: str, tag: str, index: int, payload: bytes) -> str:
    """Задание: записать один кусок в подкаталог с кусками."""
    b64 = base64.b64encode(payload).decode("ascii")
    part = "part_%04d" % index
    return "\n".join([
        "Процедура ВыполнитьЗадачу(ЛогВыполнения) Экспорт",
        _prolog(remote_dir, tag),
        '\tСоздатьКаталог(ЧастиКаталог);',
        _bsl_literal(b64),
        '\tДД = ПолучитьДвоичныеДанныеИзBase64Строки(Б64);',
        '\tПуть = ЧастиКаталог + "%s%s";' % (BS, part),
        '\tДД.Записать(Путь);',
        '\tЛогВыполнения = ЛогВыполнения + Символы.ПС + "%s: " + Новый Файл(Путь).Размер();' % part,
        '\tЛогВыполнения = ЛогВыполнения + Символы.ПС + "ГОТОВО";',
        "КонецПроцедуры",
    ])


def assemble_task(remote_dir: str, tag: str, file_name: str, parts: int,
                  size: int, sha1: str) -> str:
    """Задание: склеить куски в целевой файл, сверить размер, убрать временное."""
    add = "\n".join('\tЧасти.Добавить(ЧастиКаталог + "%spart_%04d");' % (BS, i)
                    for i in range(parts))
    return "\n".join([
        "Процедура ВыполнитьЗадачу(ЛогВыполнения) Экспорт",
        _prolog(remote_dir, tag),
        '\tЦель = Каталог + "%s";' % _bsl_str(file_name),
        '\tЧасти = Новый Массив;',
        add,
        '\tДля Каждого Ч Из Части Цикл',
        '\t\tЕсли Не Новый Файл(Ч).Существует() Тогда',
        '\t\t\tЛогВыполнения = ЛогВыполнения + Символы.ПС + "НЕТ КУСКА: " + Ч;',
        '\t\t\tВозврат;',
        '\t\tКонецЕсли;',
        '\tКонецЦикла;',
        '\tЕсли Новый Файл(Цель).Существует() Тогда',
        '\t\tУдалитьФайлы(Цель);',
        '\tКонецЕсли;',
        '\tОбъединитьФайлы(Части, Цель);',
        '\tФ = Новый Файл(Цель);',
        '\tЛогВыполнения = ЛогВыполнения + Символы.ПС + "ПУТЬ: " + Цель;',
        '\tЛогВыполнения = ЛогВыполнения + Символы.ПС + "Размер: " + Ф.Размер() + ", ожидалось: %d";' % size,
        '\tЕсли Ф.Размер() = %d Тогда' % size,
        '\t\tЛогВыполнения = ЛогВыполнения + Символы.ПС + "РАЗМЕР СОВПАЛ (sha1 источника %s)";' % sha1,
        '\tИначе',
        '\t\tЛогВыполнения = ЛогВыполнения + Символы.ПС + "РАЗМЕР НЕ СОВПАЛ";',
        '\tКонецЕсли;',
        '\tПопытка',
        '\t\tУдалитьФайлы(ЧастиКаталог);',
        '\tИсключение',
        '\tКонецПопытки;',
        '\tЛогВыполнения = ЛогВыполнения + Символы.ПС + "ГОТОВО";',
        "КонецПроцедуры",
    ])


def upload(runner, local_path: str, file_name: str = "", remote_dir: str = "",
           chunk_bytes: int = CHUNK_BYTES) -> dict:
    """
    Перелить локальный файл на машину раннера. runner — вызываемый объект вида
    Real1CRunner(CFG): runner(code) -> (status, errors, output).

    remote_dir пустой = временный каталог СЕРВЕРА, вычисляется на той стороне.
    Возвращает {"ok", "parts", "size", "sha1", "remote_path", "output"}.
    Успех подтверждается не на слово: последнее задание сверяет размер
    собранного файла с исходным и печатает фактический путь.
    """
    src = Path(local_path)
    if not src.exists():
        return {"ok": False, "reason": "нет файла: %s" % src}
    data = src.read_bytes()
    size = len(data)
    sha1 = hashlib.sha1(data).hexdigest()
    name = file_name or src.name
    # Подкаталог кусков — короткий и невыразительный, живёт только до склейки.
    tag = "t" + sha1[:8]
    pieces = [data[i:i + chunk_bytes] for i in range(0, size, chunk_bytes)] or [b""]

    log = []
    for i, piece in enumerate(pieces):
        status, errors, out = runner(chunk_task(remote_dir, tag, i, piece))
        log.append("part %d/%d: %s" % (i + 1, len(pieces), status))
        if status != "ok":
            return {"ok": False, "step": "chunk", "failed_part": i, "parts": len(pieces),
                    "reason": "кусок %d/%d не записан: %s" % (i + 1, len(pieces), status),
                    "errors": (errors or [])[:6], "output": out, "log": log}

    status, errors, out = runner(assemble_task(remote_dir, tag, name, len(pieces), size, sha1))
    ok = status == "ok" and "РАЗМЕР СОВПАЛ" in (out or "")
    remote_path = ""
    for line in (out or "").splitlines():
        if line.startswith("ПУТЬ: "):
            remote_path = line[len("ПУТЬ: "):].strip()
    return {"ok": ok, "step": "" if ok else "assemble", "parts": len(pieces),
            "size": size, "sha1": sha1, "remote_path": remote_path,
            "errors": (errors or [])[:6], "output": out, "log": log}

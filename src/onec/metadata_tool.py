#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
#8: компактные метаданные и данные вместо простыней XML.

Генерируем BSL, гоняем через тот же Real1CRunner что и run_module (Режим A —
чтение, конфигурацию НЕ трогает), разбираем текстовый вывод (ЛогВыполнения)
обратно в Python-структуры.

Три уровня describe_metadata(kind, name):
  ("", "")     -> census: счётчики по всем видам объектов конфигурации
  (kind, "")   -> index:  список имён вида + рекв/тч (или изм/рес/рекв, или знач)
  (kind, name) -> detail: полная схема объекта — реквизиты+типы, ТЧ+колонки

query_data(query_text, limit) -> Запрос.Выполнить().Выгрузить(), компактные
строки "колонка=значение|колонка=значение" вместо XML-дампа.

НАБИТО НА ЖИВЫХ ОШИБКАХ КОМПИЛЯЦИИ (проверено run_module на реальной 1С) —
не трогать без повторной проверки вживую:
  - "Знач" — зарезервированное слово (параметр по значению), нельзя как имя
    переменной ("Неопознанный оператор" в самом неожиданном месте).
  - Индексации СтрокаТаблицы["Колонка"] в BSL НЕТ. Для строки ТаблицыЗначений
    значение по номеру колонки — СтрокаТаблицы.Получить(Индекс).
    Числовая индексация коллекций (Колонки[Индекс]) — работает.
  - Метаданные.<Вид>.Найти(Имя) -> объект метаданных или Неопределено
    (динамический доступ по имени вместо Метаданные.<Вид>.<Имя>).
"""
import re

# Вид с реквизитами + табличными частями
KINDS_REQ_TAB = ["Документы", "Справочники", "ПланыВидовХарактеристик", "ПланыСчетов",
                  "ПланыОбмена", "БизнесПроцессы", "Задачи", "Обработки", "Отчеты"]
# Регистры: измерения + ресурсы + реквизиты
KINDS_REG = ["РегистрыСведений", "РегистрыНакопления", "РегистрыБухгалтерии", "РегистрыРасчета"]
# Перечисления: значения
KINDS_ENUM = ["Перечисления"]
# Плоский список (одно значение = один тип)
KINDS_FLAT = ["Константы"]

ALL_KINDS = KINDS_REQ_TAB + KINDS_REG + KINDS_ENUM + KINDS_FLAT

_NAME_RE = re.compile(r"^[A-Za-zА-Яа-яЁё0-9_]+$")
# Час у 1С НЕ дополняется нулём ("4:56:55", не "04:56:55") — \d{1,2}, не \d{2}.
# Баг найден вживую юнит-тестом parse_common_module_detail: со старым \d{2} метка
# времени не срезалась примерно 40% времени суток (когда час 0-9), портя ПЕРВУЮ
# строку разбора у ВСЕХ парсеров через _strip_ts (census/index/detail/query_rows).
_TS_RE = re.compile(r"^\d{2}\.\d{2}\.\d{4} \d{1,2}:\d{2}:\d{2}:\s*")


def _valid_name(s: str) -> bool:
    return bool(s) and bool(_NAME_RE.match(s))


def _wrap(body: str) -> str:
    return ("Процедура ВыполнитьЗадачу(ЛогВыполнения) Экспорт\n" + body +
            '\tЛогВыполнения = ЛогВыполнения + "ГОТОВО";\n'
            "КонецПроцедуры\n")


def _strip_ts(output: str) -> list:
    """Real1CRunner лепит 'дд.мм.гггг чч:мм:сс: ' перед первой строкой лога — срезаем."""
    lines = (output or "").splitlines()
    if lines:
        lines[0] = _TS_RE.sub("", lines[0])
    return lines


def _type_snippet(var: str) -> str:
    """BSL-фрагмент: строка типов реквизита/измерения/ресурса `var` (объект с .Тип) -> Тип."""
    return (f'\t\tТип = "";\n'
            f'\t\tДля Каждого Т Из {var}.Тип.Типы() Цикл\n'
            f'\t\t\tТип = Тип + ?(Тип <> "", ",", "") + Строка(Т);\n'
            f'\t\tКонецЦикла;\n')


# ==================== CENSUS ====================
def bsl_census() -> str:
    body = "".join(
        f'\tЛогВыполнения = ЛогВыполнения + "{k}=" + Строка(Метаданные.{k}.Количество()) + ";";\n'
        for k in ALL_KINDS)
    body += '\tЛогВыполнения = ЛогВыполнения + Символы.ПС;\n'
    return _wrap(body)


def parse_census(output: str) -> dict:
    lines = _strip_ts(output)
    line = lines[0] if lines else ""
    res = {}
    for part in line.split(";"):
        if "=" in part:
            k, v = part.split("=", 1)
            if v.isdigit() and int(v) > 0:
                res[k] = int(v)
    return res


# ==================== INDEX ====================
def bsl_index(kind: str) -> str:
    if kind in KINDS_REQ_TAB:
        body = (f'\tДля Каждого ОМ Из Метаданные.{kind} Цикл\n'
                f'\t\tЛогВыполнения = ЛогВыполнения + ОМ.Имя + ":" + Строка(ОМ.Реквизиты.Количество())'
                f' + "р/" + Строка(ОМ.ТабличныеЧасти.Количество()) + "тч" + Символы.ПС;\n'
                f'\tКонецЦикла;\n')
    elif kind in KINDS_REG:
        body = (f'\tДля Каждого ОМ Из Метаданные.{kind} Цикл\n'
                f'\t\tЛогВыполнения = ЛогВыполнения + ОМ.Имя + ": изм=" + Строка(ОМ.Измерения.Количество())'
                f' + " рес=" + Строка(ОМ.Ресурсы.Количество()) + " рекв=" + Строка(ОМ.Реквизиты.Количество())'
                f' + Символы.ПС;\n'
                f'\tКонецЦикла;\n')
    elif kind in KINDS_ENUM:
        body = (f'\tДля Каждого ОМ Из Метаданные.{kind} Цикл\n'
                f'\t\tЛогВыполнения = ЛогВыполнения + ОМ.Имя + ": " + Строка(ОМ.ЗначенияПеречисления.Количество())'
                f' + " знач" + Символы.ПС;\n'
                f'\tКонецЦикла;\n')
    elif kind in KINDS_FLAT:
        body = (f'\tДля Каждого ОМ Из Метаданные.{kind} Цикл\n'
                + _type_snippet("ОМ") +
                f'\t\tЛогВыполнения = ЛогВыполнения + ОМ.Имя + ": " + Тип + Символы.ПС;\n'
                f'\tКонецЦикла;\n')
    else:
        raise ValueError(f"неизвестный вид метаданных: {kind}")
    return _wrap(body)


def parse_index(output: str) -> list:
    lines = _strip_ts(output)
    return [ln for ln in lines if ln and ln != "ГОТОВО"]


# ==================== DETAIL ====================
def bsl_detail(kind: str, name: str) -> str:
    if not _valid_name(name):
        raise ValueError(f"недопустимое имя объекта: {name!r}")
    find = f'Метаданные.{kind}.Найти("{name}")'
    not_found = (f'\t\tЛогВыполнения = ЛогВыполнения + "НЕ НАЙДЕНО: {kind}.{name}" + Символы.ПС;\n')

    if kind in KINDS_REQ_TAB:
        body = (
            f'\tОМ = {find};\n'
            f'\tЕсли ОМ = Неопределено Тогда\n' + not_found +
            f'\tИначе\n'
            f'\t\tДля Каждого Рекв Из ОМ.Реквизиты Цикл\n'
            + _type_snippet("Рекв") +
            f'\t\t\tЛогВыполнения = ЛогВыполнения + Рекв.Имя + ":" + Тип + ";";\n'
            f'\t\tКонецЦикла;\n'
            f'\t\tЛогВыполнения = ЛогВыполнения + Символы.ПС;\n'
            f'\t\tДля Каждого ТЧ Из ОМ.ТабличныеЧасти Цикл\n'
            f'\t\t\tЛогВыполнения = ЛогВыполнения + "ТЧ." + ТЧ.Имя + "=[";\n'
            f'\t\t\tДля Каждого Рекв Из ТЧ.Реквизиты Цикл\n'
            + _type_snippet("Рекв") +
            f'\t\t\t\tЛогВыполнения = ЛогВыполнения + Рекв.Имя + ":" + Тип + ";";\n'
            f'\t\t\tКонецЦикла;\n'
            f'\t\t\tЛогВыполнения = ЛогВыполнения + "]" + Символы.ПС;\n'
            f'\t\tКонецЦикла;\n'
            f'\tКонецЕсли;\n')
    elif kind in KINDS_REG:
        body = (
            f'\tОМ = {find};\n'
            f'\tЕсли ОМ = Неопределено Тогда\n' + not_found +
            f'\tИначе\n'
            f'\t\tДля Каждого Рекв Из ОМ.Измерения Цикл\n'
            + _type_snippet("Рекв") +
            f'\t\t\tЛогВыполнения = ЛогВыполнения + "изм." + Рекв.Имя + ":" + Тип + ";";\n'
            f'\t\tКонецЦикла;\n'
            f'\t\tЛогВыполнения = ЛогВыполнения + Символы.ПС;\n'
            f'\t\tДля Каждого Рекв Из ОМ.Ресурсы Цикл\n'
            + _type_snippet("Рекв") +
            f'\t\t\tЛогВыполнения = ЛогВыполнения + "рес." + Рекв.Имя + ":" + Тип + ";";\n'
            f'\t\tКонецЦикла;\n'
            f'\t\tЛогВыполнения = ЛогВыполнения + Символы.ПС;\n'
            f'\t\tДля Каждого Рекв Из ОМ.Реквизиты Цикл\n'
            + _type_snippet("Рекв") +
            f'\t\t\tЛогВыполнения = ЛогВыполнения + "рекв." + Рекв.Имя + ":" + Тип + ";";\n'
            f'\t\tКонецЦикла;\n'
            f'\t\tЛогВыполнения = ЛогВыполнения + Символы.ПС;\n'
            f'\tКонецЕсли;\n')
    elif kind in KINDS_ENUM:
        body = (
            f'\tОМ = {find};\n'
            f'\tЕсли ОМ = Неопределено Тогда\n' + not_found +
            f'\tИначе\n'
            f'\t\tДля Каждого Знч Из ОМ.ЗначенияПеречисления Цикл\n'
            f'\t\t\tЛогВыполнения = ЛогВыполнения + Знч.Имя + ";";\n'
            f'\t\tКонецЦикла;\n'
            f'\t\tЛогВыполнения = ЛогВыполнения + Символы.ПС;\n'
            f'\tКонецЕсли;\n')
    elif kind in KINDS_FLAT:
        body = (
            f'\tОМ = {find};\n'
            f'\tЕсли ОМ = Неопределено Тогда\n' + not_found +
            f'\tИначе\n'
            + _type_snippet("ОМ") +
            f'\t\tЛогВыполнения = ЛогВыполнения + ОМ.Имя + ":" + Тип + Символы.ПС;\n'
            f'\tКонецЕсли;\n')
    else:
        raise ValueError(f"неизвестный вид метаданных: {kind}")
    return _wrap(body)


def parse_detail(output: str) -> dict:
    lines = _strip_ts(output)
    text = "\n".join(ln for ln in lines if ln != "ГОТОВО")
    if text.startswith("НЕ НАЙДЕНО"):
        return {"found": False, "raw": text}
    return {"found": True, "raw": text}


# ==================== QUERY ====================
def bsl_query(query_text: str, limit: int = 20) -> str:
    escaped = query_text.replace('"', '""')
    body = (
        f'\tЗапрос = Новый Запрос;\n'
        f'\tЗапрос.Текст = "{escaped}";\n'
        f'\tРез = Запрос.Выполнить();\n'
        f'\tТЗ = Рез.Выгрузить();\n'
        f'\tСчётчик = 0;\n'
        f'\tОгр = {int(limit)};\n'
        f'\tДля Каждого Стр Из ТЗ Цикл\n'
        f'\t\tСчётчик = Счётчик + 1;\n'
        f'\t\tЕсли Счётчик > Огр Тогда\n'
        f'\t\t\tЛогВыполнения = ЛогВыполнения + "...(обрезано, всего " + Строка(ТЗ.Количество()) + ")" + Символы.ПС;\n'
        f'\t\t\tПрервать;\n'
        f'\t\tКонецЕсли;\n'
        f'\t\tЗначенияСтроки = Новый Массив;\n'
        f'\t\tДля Инд = 0 По ТЗ.Колонки.Количество() - 1 Цикл\n'
        f'\t\t\tИмяКол = ТЗ.Колонки[Инд].Имя;\n'
        f'\t\t\tЗначение = Стр.Получить(Инд);\n'
        f'\t\t\tЗначенияСтроки.Добавить(ИмяКол + "=" + Строка(Значение));\n'
        f'\t\tКонецЦикла;\n'
        f'\t\tЛогВыполнения = ЛогВыполнения + СтрСоединить(ЗначенияСтроки, "|") + Символы.ПС;\n'
        f'\tКонецЦикла;\n'
        f'\tЛогВыполнения = ЛогВыполнения + "Всего строк: " + Строка(ТЗ.Количество()) + Символы.ПС;\n'
    )
    return _wrap(body)


# ==================== ОБЩИЙ МОДУЛЬ: Server/Client-флаги ====================
# #24: deploy_module однажды создал модуль ОДНОВРЕМЕННО client+server, что ломало
# резолвинг вызовов ДРУГИХ чисто серверных модулей в сервером контексте (YaXUnit
# ДобавитьСерверныйТест) с "Переменная не определена" — ложный след увёл в сторону
# "расширения не видят общие модули друг друга". Этот инструмент даёт увидеть
# реальные флаги за секунды вместо долгой охоты вслепую через run_module.
def bsl_common_module_detail(name: str) -> str:
    if not _valid_name(name):
        raise ValueError(f"недопустимое имя общего модуля: {name!r}")
    body = (
        f'\tОМ = Метаданные.ОбщиеМодули.Найти("{name}");\n'
        f'\tЕсли ОМ = Неопределено Тогда\n'
        f'\t\tЛогВыполнения = ЛогВыполнения + "НЕ НАЙДЕНО: ОбщийМодуль.{name}" + Символы.ПС;\n'
        f'\tИначе\n'
        f'\t\tЛогВыполнения = ЛогВыполнения + "Глобальный=" + Строка(ОМ.Глобальный) + ";";\n'
        f'\t\tЛогВыполнения = ЛогВыполнения + "Сервер=" + Строка(ОМ.Сервер) + ";";\n'
        f'\t\tЛогВыполнения = ЛогВыполнения + "ВнешнееСоединение=" + Строка(ОМ.ВнешнееСоединение) + ";";\n'
        f'\t\tЛогВыполнения = ЛогВыполнения + "КлиентУправляемоеПриложение=" + Строка(ОМ.КлиентУправляемоеПриложение) + ";";\n'
        f'\t\tЛогВыполнения = ЛогВыполнения + "КлиентОбычноеПриложение=" + Строка(ОМ.КлиентОбычноеПриложение) + ";";\n'
        f'\t\tЛогВыполнения = ЛогВыполнения + "ВызовСервера=" + Строка(ОМ.ВызовСервера) + ";";\n'
        f'\t\tЛогВыполнения = ЛогВыполнения + "Привилегированный=" + Строка(ОМ.Привилегированный) + ";";\n'
        f'\t\tЛогВыполнения = ЛогВыполнения + Символы.ПС;\n'
        f'\tКонецЕсли;\n'
    )
    return _wrap(body)


def parse_common_module_detail(output: str) -> dict:
    lines = _strip_ts(output)
    text = "\n".join(ln for ln in lines if ln != "ГОТОВО")
    if text.startswith("НЕ НАЙДЕНО"):
        return {"found": False, "raw": text}
    flags = {}
    for part in text.split(";"):
        if "=" in part:
            k, v = part.split("=", 1)
            flags[k] = (v.strip() == "Да")
    return {"found": True, "flags": flags}


def parse_query_rows(output: str) -> dict:
    lines = _strip_ts(output)
    rows, total, truncated = [], None, False
    for ln in lines:
        if ln == "ГОТОВО" or not ln:
            continue
        if ln.startswith("Всего строк:"):
            m = re.search(r"\d+", ln)
            total = int(m.group()) if m else None
            continue
        if ln.startswith("...(обрезано"):
            truncated = True
            continue
        row = {}
        for pair in ln.split("|"):
            if "=" in pair:
                k, v = pair.split("=", 1)
                row[k] = v
        rows.append(row)
    return {"rows": rows, "total": total, "truncated": truncated}
